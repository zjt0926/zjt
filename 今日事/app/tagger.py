# 预编译：关键词 -> 标签
_KEYWORD_MAP = {}
for tag, words in TAG_RULES:
    for w in words:
        _KEYWORD_MAP[w.lower()] = tag


def classify(title: str) -> str:
    """根据标题关键词自动分类，未命中返回 '其他'"""
    t = (title or "").lower()
    best_tag, best_pos = None, len(t) + 1
    for word, tag in _KEYWORD_MAP.items():
        pos = t.find(word)
        if pos != -1 and pos < best_pos:  # 越早出现的关键词越能代表主题
            best_tag, best_pos = tag, pos
    return best_tag or "其他"
